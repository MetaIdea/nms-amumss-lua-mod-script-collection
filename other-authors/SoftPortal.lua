-- SoftPortal
-- Dims teleporter tunnels, ancient portal tunnels, and the misty active face on teleporters.
-- Hyperdrive system warp (WARPTUNNEL) is left alone.

-- Brightness vs vanilla (~half of the previous SoftPortal pass again):
local COLOUR   = "0.08"   -- was 0.16
local PARAM2X  = "0.125"  -- was 0.25 (* of vanilla)
local LIGHTI   = "0.09"   -- was 0.18 (* of vanilla)
local LIGHTCOL = "0.175"  -- was 0.35 (* of vanilla)

local function MaterialDarken()
  return
  {
    {
      ["SPECIAL_KEY_WORDS"] = {"Name", "gMaterialColourVec4"},
      ["INTEGER_TO_FLOAT"]  = "FORCE",
      ["VALUE_CHANGE_TABLE"] =
      {
        {"X", COLOUR},
        {"Y", COLOUR},
        {"Z", COLOUR},
      }
    },
    {
      ["SPECIAL_KEY_WORDS"] = {"Name", "gMaterialParams2Vec4"},
      ["INTEGER_TO_FLOAT"]  = "FORCE",
      ["MATH_OPERATION"]    = "*",
      ["VALUE_CHANGE_TABLE"] =
      {
        {"X", PARAM2X},
      }
    },
  }
end

