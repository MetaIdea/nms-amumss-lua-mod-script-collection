local function ParticleColourDarken()
  -- Dim particle RGB; also cut mid-life alpha so mist is thinner
  local t = {}
  for _, key in ipairs({"ColourStart", "ColourMiddle", "ColourEnd"}) do
    local vct =
    {
      {"R", COLOUR},
      {"G", COLOUR},
      {"B", COLOUR},
    }
    if key == "ColourMiddle" then
      table.insert(vct, {"A", COLOUR})
    end
    table.insert(t,
    {
      ["PRECEDING_KEY_WORDS"] = {key},
      ["INTEGER_TO_FLOAT"]    = "FORCE",
      ["MATH_OPERATION"]      = "*",
      ["VALUE_CHANGE_TABLE"]  = vct,
    })
  end
  return t
end

